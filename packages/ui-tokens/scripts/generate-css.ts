/**
 * Generates apps/web/src/theme.css from the single-source tokens in
 * ../src/*.ts (Tailwind v4 is CSS-first via @theme, so this is the one
 * place token values get duplicated into CSS — regenerate after any
 * change to colors.ts/shape.ts/typography.ts rather than hand-editing
 * theme.css). Run via `pnpm --filter @icm/ui-tokens run tokens:css`.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { brand, canvas, gradDeco, gradText, ink, inkMuted, outline, status, surface } from "../src/colors";
import { radius, spacing } from "../src/shape";
import { fontFamily } from "../src/typography";

