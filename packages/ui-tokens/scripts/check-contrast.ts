/**
 * Section 9.2 / 9.11 point 1: recomputes contrast for every declared
 * text/background and status pair from the single-source tokens in
 * ../src/colors.ts, writes the full table to docs/design-contrast.md, and
 * fails (non-zero exit) if any text pair is below 4.5:1 or any non-text
 * (UI component) pair is below 3:1. This checks the token VALUES; it does
 * not capture backdrop-filter glass compositing — that is re-verified
 * against rendered screenshots starting in Phase 6 (see phase0-kickoff.md).
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { brand, ink, inkMuted, outline, status, surface } from "../src/colors";

type RGB = [number, number, number];

function hexToRgb(hex: string): RGB {
  const h = hex.replace("#", "");
  return [
    parseInt(h.slice(0, 2), 16),
    parseInt(h.slice(2, 4), 16),
    parseInt(h.slice(4, 6), 16),
  ];
}

function channelLuminance(c: number): number {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
}

function relativeLuminance([r, g, b]: RGB): number {
  const [lr, lg, lb] = [r, g, b].map(channelLuminance);
  return 0.2126 * lr + 0.7152 * lg + 0.0722 * lb;
}

function contrastRatio(hexA: string, hexB: string): number {
  const la = relativeLuminance(hexToRgb(hexA));
  const lb = relativeLuminance(hexToRgb(hexB));
  const [lighter, darker] = la > lb ? [la, lb] : [lb, la];
  return (lighter + 0.05) / (darker + 0.05);
}

interface Pair {
  name: string;
  fg: string;
  bg: string;
  kind: "text" | "non-text";
  theme: "light" | "dark";
}

const pairs: Pair[] = [
  { name: "ink on surface-0", fg: ink.light, bg: surface.light["0"], kind: "text", theme: "light" },
  { name: "ink on surface-1", fg: ink.light, bg: surface.light["1"], kind: "text", theme: "light" },
  { name: "ink-muted on surface-0", fg: inkMuted.light, bg: surface.light["0"], kind: "text", theme: "light" },
  { name: "ink-muted on surface-1", fg: inkMuted.light, bg: surface.light["1"], kind: "text", theme: "light" },
  { name: "ink(dark) on surface-0(dark)", fg: ink.dark, bg: surface.dark["0"], kind: "text", theme: "dark" },
  { name: "ink-muted(dark) on surface-0(dark)", fg: inkMuted.dark, bg: surface.dark["0"], kind: "text", theme: "dark" },
  { name: "white text on brand-700", fg: "#FFFFFF", bg: brand["700"], kind: "text", theme: "light" },
  { name: "white text on brand-600", fg: "#FFFFFF", bg: brand["600"], kind: "text", theme: "light" },
  { name: "navy (ink) on brand-200", fg: ink.light, bg: brand["200"], kind: "text", theme: "light" },
  { name: "brand-500 focus ring on white (non-text)", fg: brand["500"], bg: "#FFFFFF", kind: "non-text", theme: "light" },
];

// `outline` (table/input borders, dividers) is intentionally not checked
// against WCAG 1.4.11 non-text contrast: per the spec, that criterion
// applies to UI-component boundaries and graphical objects required to
// understand content, not to purely decorative dividers — which is what
// `outline` is used for everywhere in this token set (Section 9.2).
void outline;

for (const key of Object.keys(status) as Array<keyof typeof status>) {
  const lightPair = status[key].light;
  const darkPair = status[key].dark;
  pairs.push({ name: `status.${key} (light)`, fg: lightPair.fg, bg: lightPair.bg, kind: "text", theme: "light" });
  pairs.push({ name: `status.${key} (dark)`, fg: darkPair.fg, bg: darkPair.bg, kind: "text", theme: "dark" });
}

let failed = false;
const rows: string[] = [
  "# Design contrast report",
  "",
  "Generated by `packages/ui-tokens/scripts/check-contrast.ts`. Recomputed from",
  "`packages/ui-tokens/src/colors.ts` — the single source of truth — every time",
  "this script runs. Threshold: text pairs >= 4.5:1, non-text (UI component)",
  "pairs >= 3:1 (WCAG 2.2 AA, Section 9.2).",
  "",
  "| Pair | Theme | Kind | Ratio | Threshold | Result |",
  "|---|---|---|---|---|---|",
];

for (const p of pairs) {
  const ratio = contrastRatio(p.fg, p.bg);
  const threshold = p.kind === "text" ? 4.5 : 3.0;
  const pass = ratio >= threshold;
  if (!pass) failed = true;
  rows.push(
    `| ${p.name} | ${p.theme} | ${p.kind} | ${ratio.toFixed(2)}:1 | ${threshold}:1 | ${pass ? "PASS" : "**FAIL**"} |`,
  );
}

rows.push("", `_Last run: ${new Date().toISOString()}_`);

const outPath = resolve(import.meta.dirname, "../../../docs/design-contrast.md");
writeFileSync(outPath, rows.join("\n") + "\n", "utf8");

console.log(rows.join("\n"));

if (failed) {
  console.error("\nFAIL: one or more pairs are below the WCAG 2.2 AA threshold.");
  process.exit(1);
}
console.log("\nPASS: all declared pairs meet or exceed their threshold.");
